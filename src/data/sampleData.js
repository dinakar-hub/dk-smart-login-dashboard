export function withRunStatus(run) {
  const done = run.cases.filter((item) => item.result !== "Not Run").length;
  const finished = done === run.cases.length;
  return {
    ...run,
    done,
    progress: Math.round((done / run.cases.length) * 100),
    status: finished ? "Completed" : "In Progress",
  };
}
